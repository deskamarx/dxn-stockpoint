/**
 * Tiny dependency-free PDF writer.
 *
 * It produces a real PDF 1.4 document with selectable Helvetica text, which is
 * enough for receipts, invoices and tabular reports and keeps the app fully
 * offline (no CDN, no paid library). Text outside WinAnsi is transliterated so
 * a stray emoji can never corrupt the file.
 */

const PAGE_W = 595.28; // A4 points
const PAGE_H = 841.89;
const MARGIN = 46;
const FONT = { normal: 'F1', bold: 'F2', mono: 'F3' };

function latin(text) {
  return String(text ?? '')
    .replace(/৳/g, 'BDT ')
    .replace(/[–—]/g, '-')
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/[^\x09\x0A\x0D\x20-\xFF]/g, '?');
}

function pdfEscape(text) {
  return latin(text).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)').replace(/\r/g, '');
}

function wrap(text, maxChars) {
  const words = latin(text).split(/\s+/).filter(Boolean);
  const lines = [];
  let current = '';
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (candidate.length <= maxChars) {
      current = candidate;
    } else {
      if (current) lines.push(current);
      if (word.length > maxChars) {
        let rest = word;
        while (rest.length > maxChars) {
          lines.push(rest.slice(0, maxChars));
          rest = rest.slice(maxChars);
        }
        current = rest;
      } else {
        current = word;
      }
    }
  }
  if (current) lines.push(current);
  return lines.length ? lines : [''];
}

function estimateWidth(text, size, bold = false) {
  return latin(text).length * size * (bold ? 0.56 : 0.52);
}

/**
 * @param {object} doc
 * @param {string} doc.title
 * @param {string} [doc.subtitle]
 * @param {Array<string|object>} doc.lines  strings or {text, bold, size, gap, align, rule}
 * @param {string} [doc.footer]
 * @param {string} [doc.pageLabel]
 * @returns {Uint8Array}
 */
export function buildPdf(doc = {}) {
  const title = doc.title || 'Stockpoint';
  const subtitle = doc.subtitle || '';
  const footer = doc.footer || 'Generated by Mohammadpur Stock Point';
  const items = Array.isArray(doc.lines) ? doc.lines : [];
  const pages = [];
  let content = [];
  let y = PAGE_H - MARGIN;

  const startPage = () => {
    content = [];
    y = PAGE_H - MARGIN;
    if (title) {
      content.push(`BT /${FONT.bold} 17 Tf ${MARGIN} ${y} Td (${pdfEscape(title)}) Tj ET`);
      y -= 22;
    }
    if (subtitle) {
      content.push(`BT /${FONT.normal} 9 Tf ${MARGIN} ${y} Td (${pdfEscape(subtitle)}) Tj ET`);
      y -= 14;
    }
    content.push(`0.85 w 0.8 0.8 0.8 RG ${MARGIN} ${y} m ${PAGE_W - MARGIN} ${y} l S`);
    y -= 18;
  };

  const endPage = () => {
    const label = `Page ${pages.length + 1}`;
    content.push(`BT /${FONT.normal} 8 Tf ${MARGIN} ${MARGIN - 16} Td (${pdfEscape(footer)}) Tj ET`);
    content.push(`BT /${FONT.normal} 8 Tf ${PAGE_W - MARGIN - 40} ${MARGIN - 16} Td (${pdfEscape(label)}) Tj ET`);
    pages.push(content.join('\n'));
  };

  startPage();

  for (const raw of items) {
    const item = typeof raw === 'string' ? { text: raw } : (raw || {});
    if (item.pageBreak) {
      endPage();
      startPage();
      continue;
    }
    if (item.rule) {
      if (y < MARGIN + 40) { endPage(); startPage(); }
      content.push(`0.6 w 0.75 0.75 0.75 RG ${MARGIN} ${y} m ${PAGE_W - MARGIN} ${y} l S`);
      y -= 12;
      continue;
    }
    const size = Number(item.size || 10);
    const bold = Boolean(item.bold);
    const font = item.mono ? FONT.mono : bold ? FONT.bold : FONT.normal;
    const maxChars = Math.max(12, Math.floor((PAGE_W - MARGIN * 2) / (size * (item.mono ? 0.6 : 0.5))));
    const rows = item.nowrap ? [latin(item.text)] : wrap(item.text, maxChars);
    for (const row of rows) {
      if (y < MARGIN + 30) { endPage(); startPage(); }
      let x = MARGIN;
      if (item.align === 'right') x = PAGE_W - MARGIN - estimateWidth(row, size, bold);
      if (item.align === 'center') x = (PAGE_W - estimateWidth(row, size, bold)) / 2;
      content.push(`BT /${font} ${size} Tf ${x.toFixed(2)} ${y.toFixed(2)} Td (${pdfEscape(row)}) Tj ET`);
      y -= size + Number(item.gap ?? 4);
    }
    if (item.space) y -= Number(item.space);
  }

  endPage();

  // ── Assemble objects ──────────────────────────────────────────────────────
  const objects = [];
  const add = (body) => {
    objects.push(body);
    return objects.length; // 1-based object id
  };

  const catalogId = add('');
  const pagesId = add('');
  const fontNormal = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
  const fontBold = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');
  const fontMono = add('<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>');

  const pageIds = [];
  for (const stream of pages) {
    const contentId = add(`<< /Length ${new TextEncoder().encode(stream).length} >>\nstream\n${stream}\nendstream`);
    const pageId = add(`<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] /Resources << /Font << /F1 ${fontNormal} 0 R /F2 ${fontBold} 0 R /F3 ${fontMono} 0 R >> >> /Contents ${contentId} 0 R >>`);
    pageIds.push(pageId);
  }

  objects[catalogId - 1] = `<< /Type /Catalog /Pages ${pagesId} 0 R >>`;
  objects[pagesId - 1] = `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${pageIds.length} >>`;

  const header = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n';
  let body = header;
  const offsets = [0];
  objects.forEach((object, index) => {
    offsets.push(body.length);
    body += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefOffset = body.length;
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i += 1) {
    body += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  body += `trailer\n<< /Size ${objects.length + 1} /Root ${catalogId} 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  const bytes = new Uint8Array(body.length);
  for (let i = 0; i < body.length; i += 1) bytes[i] = body.charCodeAt(i) & 0xFF;
  return bytes;
}

export function pdfBlob(bytes) {
  return new Blob([bytes], { type: 'application/pdf' });
}

export function downloadPdf(filename, bytes) {
  const blob = pdfBlob(bytes);
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}

/** Printable receipt/invoice PDF for an order. */
export function receiptPdf(order, settings = {}) {
  const money = (value) => `BDT ${Number(value || 0).toFixed(2)}`;
  const lines = [];
  lines.push({ text: settings.business_address || 'Mohammadpur, Dhaka', size: 9, align: 'center' });
  if (settings.business_phone) lines.push({ text: `Phone: ${settings.business_phone}`, size: 9, align: 'center' });
  lines.push({ rule: true });
  lines.push({ text: `Invoice: ${order.order_number || 'PENDING'}`, bold: true, size: 11 });
  lines.push({ text: `Date: ${new Date(order.created_at || Date.now()).toLocaleString()}`, size: 9 });
  lines.push({ text: `Customer: ${order.customer_name || 'Walk-in customer'}`, size: 9 });
  if (order.dxn_member_id) lines.push({ text: `DXN member: ${order.dxn_member_id}`, size: 9 });
  lines.push({ rule: true });
  lines.push({ text: 'ITEM', bold: true, size: 8 });
  for (const item of order.items || []) {
    lines.push({ text: item.name || `Product ${item.product_id}`, size: 9, gap: 2 });
    lines.push({
      text: `${item.quantity} x ${money(item.unit_price)}   =   ${money(item.line_total ?? item.unit_price * item.quantity)}`,
      size: 9,
      align: 'right',
      gap: 6,
    });
  }
  lines.push({ rule: true });
  lines.push({ text: `Subtotal: ${money(order.subtotal)}`, size: 9, align: 'right' });
  if (Number(order.discount) > 0) lines.push({ text: `Discount: -${money(order.discount)}`, size: 9, align: 'right' });
  lines.push({ text: `TOTAL: ${money(order.total_amount)}`, bold: true, size: 13, align: 'right', gap: 8 });
  if (order.amount_paid !== undefined) {
    lines.push({ text: `Paid: ${money(order.amount_paid)}`, size: 9, align: 'right' });
    if (Number(order.due_amount) > 0) lines.push({ text: `Due: ${money(order.due_amount)}`, bold: true, size: 10, align: 'right' });
  }
  if (Array.isArray(order.payments) && order.payments.length) {
    lines.push({ rule: true });
    for (const payment of order.payments) {
      lines.push({ text: `${payment.method}: ${money(payment.amount)}${payment.reference ? ` (${payment.reference})` : ''}`, size: 8 });
    }
  }
  if (order.note) lines.push({ text: `Note: ${order.note}`, size: 8, gap: 6 });
  lines.push({ text: settings.receipt_footer || 'Thank you for your purchase.', size: 9, align: 'center', gap: 4 });
  return buildPdf({
    title: settings.branch_name || 'Mohammadpur Stock Point',
    subtitle: 'Sales invoice / money receipt',
    lines,
    footer: `${settings.branch_name || 'Stockpoint'} - ${order.order_number || 'pending'}`,
  });
}
